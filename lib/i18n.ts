const DICTIONARIES: Readonly<Record<Locale, Dictionary>> = {
  en: EN,
  "zh-CN": ZH_CN,
  ja: JA,
  es: ES,
};

export type TranslationParams = Readonly<
  Record<string, string | number>
>;

/**
 * Translate a stable UI key and interpolate `{name}`-style parameters.
 * Unknown locales resolve to English. An unknown runtime key is returned as-is,
 * which keeps a rendering failure visible without crashing the interface.
 */
export function t(
  locale: Locale | string | null | undefined,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const dictionary = DICTIONARIES[resolveLocale(locale)];
  const runtimeKey = key as string;
  const template =
    (dictionary as Readonly<Record<string, string>>)[runtimeKey] ??
    (EN as Readonly<Record<string, string>>)[runtimeKey] ??
    runtimeKey;

  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (token, name: string) => {
    if (!Object.prototype.hasOwnProperty.call(params, name)) return token;
    return String(params[name]);
  });
}

