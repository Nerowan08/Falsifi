export function resolveLocale(
  candidate?: string | readonly string[] | null,
): Locale {
  const requested = Array.isArray(candidate)
    ? candidate.find((value) => value.trim().length > 0)
    : candidate;

  if (typeof requested !== "string") return "en";

  const normalized = requested.trim().replaceAll("_", "-").toLowerCase();
  if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
  if (normalized === "ja" || normalized.startsWith("ja-")) return "ja";
  if (normalized === "es" || normalized.startsWith("es-")) return "es";
  return "en";
}

